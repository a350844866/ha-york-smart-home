def describe_code(code: str) -> dict[str, str]:
    """Description of a fault code (two hex digits), case-insensitive.

    Returns ``description`` (the app's own text, else the table's reason) and
    ``reason_two`` / ``reason_three`` when the table has them; an empty dict
    for codes the app does not know.
    """
    key = code.strip().upper()
    reason, reason_two, reason_three = TROUBLE_CODES.get(key, ("", "", ""))
    result = {}
    if description := APP_ALARM_TEXTS.get(key) or reason:
        result["description"] = description
    if reason_two:
        result["reason_two"] = reason_two
    if reason_three:
        result["reason_three"] = reason_three
    return result
